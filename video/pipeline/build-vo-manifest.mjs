/**
 * Build scripts/vo.json from the agent team's output, applying the critic's
 * line fixes.
 *
 * The team returns scripts as structured objects (vo + scene + animation per
 * line). The TTS pipeline only needs the spoken text and the gaps, so this
 * flattens them — and applies the completeness critic's replacements on the
 * way, because several of them are TTS-specific defects that only show up when
 * the line is spoken:
 *
 *   - "auth" is a spelling, not a word; Gemini renders it inconsistently.
 *   - Four terminal stops in one line IS the "pauses are too long" complaint,
 *     just spelled with full stops instead of silence.
 *   - "calls" in a film about API spend has two meanings.
 *   - "README" is a coin flip between "read-me" and spelling it out.
 *   - Seven spoken "Chapter N" announcements add seven dead sentence-final
 *     stops to a tutorial already criticised for pausing.
 *
 * Usage: node pipeline/build-vo-manifest.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

const team = JSON.parse(readFileSync(join(ROOT, "scripts", "team-output.json"), "utf8"));

/** Critic's replacements, keyed by "<scriptId>/<lineId>". */
const FIXES = {
  "explainer/01-wince":
    "Your most expensive model just renamed a variable. In the same chat, it judged an authentication boundary.",
  "explainer/03-turn":
    "You didn't install a tool — you hired a manager. He runs the team; you only talk to him.",
  "explainer/04-interview":
    "He interviews you first — batches of at most four, each with his recommendation.",
  "explainer/07-implementers":
    "Implementers take one story each, on their own branch, with an empty scrollback. What they find goes into the journal in your repo — so the reviewer starts already knowing it, and a crash or a compaction changes nothing.",
  "explainer/10-floor":
    "Security review always gets the strongest tier — and no flag or cost setting can lower it.",
  "explainer/16-bill":
    "Then the bill. Four and a half million tokens, across four hundred and four requests.",
  "explainer/17-overhead":
    "Fifty-five percent of those tokens were the manager's own context. The manager gets its own row, so nothing hides inside the total.",
  "explainer/19-hooks-decide":
    "None of this is a prompt asking nicely. A hook decides before the tool ever runs.",
  "explainer/25-close":
    "That was one request. You made two decisions. The team did the rest.",
  // "Not how a README describes it" survived the README -> "the docs" rule as
  // "how a the docs describes it" and was spoken that way in a finished cut.
  // The GLOBAL guard below stops the article stranding; this restores the
  // verb agreement the substitution also broke.
  "onboarding/05-setup":
    "Slash tyran setup, once per repository. It reads how the repo is really worked. Not how the docs describe it.",
};

/** Substring repairs applied to every line in every script. */
const GLOBAL = [
  [/\bauth boundary\b/g, "authentication boundary"],
  [/\ban auth check\b/g, "an authentication check"],
  // Order matters: "a README" has to go before the bare word, or the article
  // is left stranded in front of a plural ("a the docs").
  [/\ba README\b/g, "the docs"],
  [/\bREADME\b/g, "the docs"],
  [/\bgitleaks\b/g, "gitleaks"],
];

/** Spoken "Chapter N" survives on these ids only; elsewhere it is stripped. */
const KEEP_CHAPTER = new Set(["01", "08"]);

function repair(scriptId, line) {
  const key = `${scriptId}/${line.id}`;
  let vo = FIXES[key] || line.vo;
  for (const [re, to] of GLOBAL) vo = vo.replace(re, to);

  if (scriptId === "onboarding" && !KEEP_CHAPTER.has(line.id)) {
    // drop a leading spoken chapter announcement; the drawn card still carries it
    vo = vo.replace(/^\s*Chapter\s+(one|two|three|four|five|six|seven|eight)\.\s*/i, "");
  }
  return vo.trim();
}

const scripts = [team.explainer, ...team.slate].filter(Boolean);

const videos = {};
for (const s of scripts) {
  videos[s.id] = {
    _title: s.title,
    _aspect: s.aspect,
    _purpose: s.purpose,
    lead: s.lead ?? 0.35,
    gap: s.gap ?? 0.45,
    tail: s.tail ?? 2.6,
    lines: s.lines.map((l) => {
      const out = { id: l.id, text: repair(s.id, l) };
      if (typeof l.gapAfter === "number") out.gapAfter = Math.min(0.8, Math.max(0.3, l.gapAfter));
      return out;
    }),
  };
}

const manifest = {
  _comment:
    "GENERATED by pipeline/build-vo-manifest.mjs from scripts/team-output.json (the agent team's scripts) with the completeness critic's line fixes applied. Edit team-output.json or the FIXES table in the builder, not this file — it is overwritten.",
  _voice_note:
    "gemini-3.1-flash-tts-preview. NO speed parameter: OpenAI's speed time-stretches the audio and that artifact is what sounded synthetic. Timings are packed against measured audio; each line declares only the gap that follows it.",
  _direction_note:
    "Gemini's direction must stay SHORT and plainly instructional — a longer characterful brief trips a non-configurable PROHIBITED_CONTENT block on benign lines (0/3 vs 3/3 measured). Energy level L2 on pipeline/energy-ladder.mjs: L1 was judged too hot, L3/L4 too flat. Voice Alnilam; Charon is the sanctioned alternative.",
  provider: "gemini",
  model: "gemini-3.1-flash-tts-preview",
  voice: "Alnilam",
  direction: "Speak clearly at a natural pace, with quiet confidence and a little warmth.",
  direction_openai:
    "Confident and warm, never hyped and never flat. Push gently through each line; no dramatic pauses. Read commands and file paths crisply.",
  videos,
};

writeFileSync(join(ROOT, "scripts", "vo.json"), JSON.stringify(manifest, null, 2) + "\n");

let fixed = 0;
for (const s of scripts) for (const l of s.lines) if (FIXES[`${s.id}/${l.id}`]) fixed++;

console.log(`wrote scripts/vo.json`);
for (const s of scripts) {
  const words = s.lines.reduce((a, l) => a + l.vo.split(/\s+/).length, 0);
  console.log(`  ${s.id.padEnd(12)} ${String(s.lines.length).padStart(2)} lines · ~${words} words · ${s.aspect}`);
}
console.log(`\ncritic fixes applied: ${fixed} whole-line, plus global repairs`);
