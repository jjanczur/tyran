// ------------------------------------------------------- the write channel

/** A request body big enough for any setting and small enough to ignore. */
const MAX_BODY_BYTES = 64 * 1024;

/**
 * Read a JSON request body, or reject it.
 *
 * Three refusals, all deliberate. A body over the cap is dropped rather than
 * buffered, because this server has no reason to hold a megabyte of anything.
 * A body that is not `application/json` is refused BEFORE it is read — that
 * content type is what forces a browser to preflight a cross-origin POST, and
 * accepting `text/plain` here would hand back the exact hole the preflight
 * closes. And anything that is not a JSON object is refused, so a handler
 * never reasons about a string that happens to have a `.value`.
 */
function readJsonBody(req) {
  return new Promise((resolve_, reject) => {
    const type = String(req.headers['content-type'] ?? '').split(';')[0].trim().toLowerCase();
    if (type !== 'application/json') {
      reject(new SettingsError('this route takes application/json'));
      return;
    }
    let size = 0;
    const chunks = [];
    req.on('data', (chunk) => {
      size += chunk.length;
      if (size > MAX_BODY_BYTES) {
        // Reject, but do NOT destroy the socket: the route's 400 is written on
        // the next tick, and tearing the connection down first meant the
        // client saw a network error instead of the sentence explaining what
        // was wrong. Pausing stops us reading the rest without discarding the
        // channel the answer goes out on.
        req.pause();
        reject(new SettingsError(`request body is larger than ${MAX_BODY_BYTES} bytes`));
        return;
      }
      chunks.push(chunk);
    });
    req.on('error', (err) => reject(err));
    req.on('end', () => {
      let parsed;
      try {
        parsed = JSON.parse(Buffer.concat(chunks).toString('utf8'));
      } catch {
        reject(new SettingsError('request body is not JSON'));
        return;
      }
      if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
        reject(new SettingsError('request body must be a JSON object'));
        return;
      }
      resolve_(parsed);
    });
  });
}

/**
 * `Origin`, on top of the `Host` pin the whole server already carries.
 *
 * The two answer different questions and neither covers the other. `Host` says
 * which name the client dialled, which stops DNS rebinding. `Origin` says
 * which page is asking, which is the only thing that distinguishes the board's
 * own fetch from a POST issued by some other tab the operator has open. A
 * request with no `Origin` at all is allowed: that is `curl`, and a local
 * process that can reach loopback needs no browser's help — see the honest
 * statement of what this does and does not defend in `docs/board.md`.
 */
function originAllowed(req) {
  const origin = req.headers.origin;
  if (origin === undefined || origin === 'null') return true;
  try {
    const { hostname } = new URL(String(origin));
    return hostname === '127.0.0.1' || hostname === 'localhost' || hostname === '[::1]' || hostname === '::1';
  } catch {
    return false;
  }
}

const sendJson = (res, status, body) => {
  res.writeHead(status, { 'content-type': 'application/json; charset=utf-8' });
  res.end(JSON.stringify(body) + '\n');
};

/**
 * Answer one open question, from the page instead of from a terminal.
 *
 * The request supplies exactly two things: WHICH ask, and the operator's own
 * words. Everything else — the question, the recorded default, the ticket, the
 * gate id — is read back out of the journal, which is the same guarantee
 * `answer apply` makes about its sheet: nothing you type can change what was
 * asked. The append itself is `answerOne`, unchanged and unwrapped, so the
 * lock, the re-check and the decision-before-gate ordering are the ones the
 * CLI already uses.
 */
function handleAnswer(dir, body) {
  const kind = String(body.kind ?? '');
  const init = String(body.init ?? '');
  const text = typeof body.answer === 'string' ? body.answer : '';

  const { asks } = openAsks(dir);
  const { answerable } = partitionAsks(asks);
  const ask = answerable.find((a) => a.kind === kind && a.init === init);
  if (ask === undefined) {
    throw new SettingsError(
      `no open question "${kind}" in "${init}" — it may have been answered in a terminal since this page loaded. Reload.`,
    );
  }
  const trimmed = text.trim();
  const problem = answerProblem(trimmed);
  if (problem !== null) throw new SettingsError(`that answer ${problem}`);

  const verdict = classify(trimmed, ask);
  if (verdict.mode === 'open') throw new SettingsError(verdict.why ?? 'nothing to record');
  const outcome = answerOne(ask, verdict);
  if (outcome.skipped !== undefined) throw new SettingsError(outcome.skipped);

  // A board still showing an answered question is worse than one that never
  // showed it. Re-render before replying, so the reload the page does next is
  // already correct.
  reRender(dir, new Map([[ask.init, ask.journal]]));
  console.log(`board: answered ${ask.init}/${ask.kind} (${verdict.mode}) -> decision ${outcome.decision}`);
  return { ok: true, kind: ask.kind, init: ask.init, mode: verdict.mode, decision: outcome.decision, recorded: verdict.text };
}

/**
 * Apply one edit and write it, or change nothing and say why.
 *
 * The write itself is `writeAtomic` — the same rename-into-place the
 * projections use — so a config file can never be found half-written, however
 * the process dies.
 */
function handleSettingsWrite(dir, route, body) {
  // `confirm` is only ever compared for equality against the value the server
  // itself computed, so a caller cannot widen anything by sending a truthy
  // flag — it has to name the exact change it is making.
  const confirm = typeof body.confirm === 'string' ? body.confirm : null;
  const applied =
    route === 'config'
      ? applySetting(dir, String(body.id ?? ''), body.value, confirm)
      : applyPolicyClass(dir, body.path === null || body.path === undefined ? null : String(body.path), String(body.class ?? ''), confirm);
  // Compare-and-swap. `applySetting` reads the whole file and computes a whole
  // replacement, so a second writer between the read and the write would have
  // its change silently discarded — and both writers would report success.
  // In-process that cannot interleave (this handler is one synchronous block),
  // but two boards on one directory, or a board and a terminal, are ordinary.
  if (readFileSync(applied.file, 'utf8') !== applied.before_text) {
    throw new SettingsError(
      `${applied.file} changed underneath this edit — something else wrote it while the page was open. Nothing was written; reload and try again.`,
    );
  }
  writeAtomic(applied.file, applied.text);
  // The operator's terminal is the audit trail. A change made from a web page
  // that left no trace anywhere a person looks is how a settings screen turns
  // into a thing nobody trusts.
  console.log(`board: wrote ${applied.file} — ${applied.path.join('.')}: ${JSON.stringify(applied.before)} -> ${JSON.stringify(applied.after)}`);
  return { ok: true, file: applied.file, path: applied.path, before: applied.before, after: applied.after };
}

// ------------------------------------------------------------------- CLI

const BOOLEAN_FLAGS = ['check', 'serve', 'write', 'open', 'detach', 'stop', 'status'];
const VALUE_FLAGS = ['dir', 'port'];
// Repeatable, unlike VALUE_FLAGS: sources are the union over every directory
// given, exactly like cost.mjs's own `--transcripts`.
const REPEATABLE_FLAGS = ['transcripts'];

function parseArgs(argv) {
  const flags = {
    dir: '.tyran', port: 4173, check: false, serve: false, write: false, open: false,
    detach: false, stop: false, status: false, transcripts: [],
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith('--')) throw new UsageError(`unexpected argument "${arg}"`);
    const name = arg.slice(2);
    if (BOOLEAN_FLAGS.includes(name)) flags[name] = true;
    else if (VALUE_FLAGS.includes(name)) {
      const value = argv[i + 1];
      if (value === undefined) throw new UsageError(`flag --${name} needs a value`);
      flags[name] = name === 'port' ? Number(value) : value;
      i += 1;
    } else if (REPEATABLE_FLAGS.includes(name)) {
      const value = argv[i + 1];
      if (value === undefined) throw new UsageError(`flag --${name} needs a value`);
      flags[name].push(value);
      i += 1;
    } else throw new UsageError(`unknown flag --${name}`);
  }
  if (!Number.isInteger(flags.port) || flags.port <= 0 || flags.port > 65535) {
    throw new UsageError('--port must be an integer in (0, 65535]');
  }
  return flags;
}

export const BOARD_USAGE =
  'usage: board.mjs [--dir <.tyran>] [--check]\n' +
  '                 [--serve|--detach [--port <n>] [--write] [--open] [--transcripts <dir>]...]\n' +
  '                 [--status] [--stop]';

function main() {
  // Answered before parsing, because the parser's job is to refuse what it
  // does not know and `--help` is exactly that to every parser here.
  if (wantsHelp(process.argv.slice(2))) {
    console.log(BOARD_USAGE);
    return;
  }
  let flags;
  try {
    flags = parseArgs(process.argv.slice(2));
  } catch (err) {
    if (!(err instanceof UsageError)) throw err;
    console.error(`board: ${err.message}`);
    console.error(BOARD_USAGE);
    process.exit(2);
  }
  // `--detach` is `--serve` that returns. Every flag describing HOW to serve
  // therefore has to accept either, or the detached form would refuse exactly
  // the arguments it exists to be given.
  const serving = flags.serve || flags.detach;
  if (flags.serve && flags.detach) {
    console.error('board: --serve and --detach are the same server, one holding the terminal and one not — pass one');
    process.exit(2);
  }
  if (flags.write && !serving) {
    console.error('board: --write only means anything with --serve or --detach (it is what the served page may edit)');
    process.exit(2);
  }
  if (flags.open && !serving) {
    // Same refusal as --write and --transcripts, for the same reason: there is
    // no URL to open without a server, and a flag that silently does nothing
    // reads as configuration.
    console.error('board: --open only means anything with --serve or --detach (there is no URL to open without it)');
    process.exit(2);
  }
  if (flags.transcripts.length > 0 && !serving) {
    console.error(
      'board: --transcripts only means anything with --serve or --detach (it is what /cost.json reads instead of ' +
        'the derived transcript directory)'
    );
    process.exit(2);
  }
  const dir = resolve(flags.dir);
  if (!existsSync(dir)) {
    console.error(`board: no such directory ${dir}`);
    process.exit(2);
  }
  // `--dir` wants the `.tyran` directory, and pointing it at the repo root
  // instead is the obvious typo. Since the renderer creates `state/` where it
  // is told to, that typo used to succeed silently: a `state/` directory
  // appearing in the project root, and an empty board reporting that all is
  // well about a repo whose real journals sit one level down. Any ONE of these
  // three is enough to recognise a Tyran directory, including a freshly set up
  // one that has no initiative yet.
  const looksLikeTyran = ['state', 'config.yaml', 'policies'].some((name) => existsSync(join(dir, name)));
  if (!looksLikeTyran) {
    console.error(
      `board: ${dir} does not look like a .tyran directory — it has no state/, config.yaml or policies/. ` +
        'Point --dir at .tyran itself (run /tyran:setup first if this repo has not adopted Tyran).',
    );
    process.exit(2);
  }
  const outDir = join(dir, 'state');

  // ---- the three routes that talk ABOUT a server rather than being one ----
  //
  // All three are async, and `main` stays sync for everything else on
  // purpose: the rendering path is the one every test and every hook drives,
  // and making it return a promise would change the shape of a contract that
  // has nothing to do with servers.
  if (flags.status) {
    findLiveServer(dir, flags.port).then((live) => {
      if (live === null) {
        console.log(
          `board: no server is answering for ${dir} ` +
            `(tried the recorded port, if any, then ${flags.port}-${flags.port + PORT_SEARCH_SPAN - 1}) — ` +
            `start one with: node scripts/board.mjs --dir ${dir} --detach --write`,
        );
        process.exitCode = 1;
        return;
      }
      console.log(
        `board: serving ${urlFor(live.port)} (pid ${live.health.pid ?? '?'}; ` +
          `${live.health.write ? 'Settings can edit config.yaml and autonomy.yaml' : 'read-only'})`,
      );
    });
    return;
  }
  if (flags.stop) {
    stopServer(dir).then((result) => {
      if (result.stopped) {
        console.log(`board: stopped the server on port ${result.port} (pid ${result.pid})`);
        return;
      }
      console.error(`board: ${result.reason}`);
      process.exitCode = 1;
    });
    return;
  }
  if (flags.detach) {
    startDetached(dir, { port: flags.port, write: flags.write, open: flags.open, transcripts: flags.transcripts })
      .then((result) => {
        if (result.error) {
          console.error(`board: ${result.error}`);
          process.exitCode = 2;
          return;
        }
        // "Already running" is a SUCCESS, and saying which one it is matters:
        // this command is meant to be safe to run on every session start, so
        // its ordinary outcome is that there was nothing to do.
        if (result.reused) {
          console.log(`board: already serving ${result.url} (pid ${result.pid ?? '?'})`);
          // Start-time flags do not reach a server that is already up. Saying
          // so is the whole fix: the command reported success, the operator
          // reloaded the tab, and nothing had changed — with `--transcripts`
          // that is the remedy the Spend tab itself recommends.
          const inert = [];
          if (flags.transcripts.length > 0) inert.push('--transcripts');
          if (flags.write && !result.write) inert.push('--write');
          if (inert.length > 0) {
            console.log(
              `board: ${inert.join(' and ')} had NO effect — that server was started separately. ` +
                `To change how it runs: node scripts/board.mjs --dir ${dir} --stop, then start it again.`,
            );
          }
          return;
        }
        console.log(
          `board: serving ${result.url} (pid ${result.pid ?? '?'}; ` +
            `${flags.write ? 'Settings can edit config.yaml and autonomy.yaml' : 'read-only'}; ` +
            `stop it with: node scripts/board.mjs --dir ${dir} --stop)`,
        );
      });
    return;
  }

  if (flags.serve) {
    // Loopback-only, re-rendered per request so it is always fresh. No
    // filesystem path is ever derived from the URL.
    //
    // Not quite read-only, and the exception is worth stating rather than
    // discovering: `/cost.json` refreshes the machine-local spend cache at
    // `state/cost.json`. Nothing else is written, and that file is a
    // gitignored runtime artefact — no journal, no projection, nothing
    // committed.
    const server = createServer((req, res) => {
      try {
        // Binding to loopback is not enough on its own: any web page the
        // operator visits can resolve its own hostname to 127.0.0.1 and read
        // this board — which carries journal content from foreign
        // repositories — straight out of the browser (DNS rebinding). A
        // browser cannot forge the Host header, so pinning it to the literal
        // loopback names closes that path.
        const host = String(req.headers.host ?? '').replace(/:\d+$/, '');
        if (host !== '127.0.0.1' && host !== 'localhost' && host !== '[::1]') {
          res.writeHead(403, { 'content-type': 'text/plain' });
          res.end('forbidden: this board answers to 127.0.0.1 only\n');
          return;
        }
        // ---- settings: the routes that read and write config -----------
        //
        // Config is served rather than embedded for the same reason spend is:
        // it is not journal state, it is not a projection, and writing it into
        // `board.json` would break the byte-exact `--check` contract. Over
        // `file://` the fetch fails and the tab says how to open the board
        // with a server, which is the honest answer.
        // The MACHINE-LOCAL half of "is this run supposed to be running".
        // `.tyran/STOP` is committed and travels in the artefact; the pause
        // marker, the resume watcher and the usage sidecar are gitignored and
        // different on every machine, so they are served — the same split, and
        // the same argument, spend already makes.
        // The liveness answer, and the ONLY reliable one. A caller asking
        // "is a board already up for this repo" cannot use the recorded pid —
        // see board-daemon.mjs for why — so it asks the server itself, and
        // `dir` is what stops ANOTHER repository's board (same program, same
        // route) from answering yes on this one's behalf.
        if (req.url === HEALTH_ROUTE) {
          sendJson(res, 200, { tyran_board: true, schema: 1, dir, pid: process.pid, port: flags.port, write: flags.write });
          return;
        }
        if (req.url === '/run.json') {
          try {
            sendJson(res, 200, { schema: 1, ...runState(resolve(dir, '..')) });
          } catch (err) {
            // A run-state failure must never take the board down with it.
            sendJson(res, 503, { schema: 1, error: String(err?.message ?? err) });
          }
          return;
        }
        if (req.url === '/settings.json') {
          sendJson(res, 200, { ...readSettings(dir), writable: flags.write });
          return;
        }
        // An initiative's own documents, which the board could name and not
        // open. A GET behind the same Host pin as everything else, and NOT
        // behind `--write`: reading a PLAN.md is what this whole page does,
        // and the flag draws its line at changing the repository.
        //
        // The route takes an initiative and a FILE NAME. It takes no path,
        // because a route that takes a path is a route whose safety is a
        // filter — see readInitiativeDoc for the two closed sets that replace
        // one. The old comment on `initiativeFiles` said this board derives a
        // filesystem path from no URL at all; it still does not.
        if (req.url.startsWith('/doc.json?') || req.url === '/doc.json') {
          const q = new URLSearchParams(req.url.slice(req.url.indexOf('?') + 1));
          const doc = readInitiativeDoc(dir, String(q.get('init') ?? ''), String(q.get('name') ?? ''));
          if (doc.ok !== true) {
            sendJson(res, doc.status, { ok: false, error: doc.error });
            return;
          }
          const { ok, status, ...payload } = doc;
          sendJson(res, 200, payload);
          return;
        }
        if (req.url === '/settings/config' || req.url === '/settings/policy' || req.url === '/answer') {
          const route = req.url === '/answer' ? 'answer' : req.url.slice('/settings/'.length);
          if (req.method !== 'POST') {
            sendJson(res, 405, { ok: false, error: 'this route takes POST' });
            return;
          }
          // Writes are OFF unless the operator asked for them on the command
          // line. A board someone left running is a board that can be reached
          // by anything on this machine, and the difference between reading
          // that and editing the autonomy policy through it is the difference
          // this flag exists to make. The refusal names the flag, because a
          // 403 an operator cannot act on is just a bug report.
          // One flag for every route that writes. Answering a question and
          // editing the autonomy policy are different acts, but they are the
          // same decision for the operator: whether this board may change the
          // repository at all.
          if (!flags.write) {
            sendJson(res, 403, {
              ok: false,
              error: 'this board is read-only. Restart it with: npx @jjanczur/tyran board --serve --write',
            });
            return;
          }
          if (!originAllowed(req)) {
            sendJson(res, 403, { ok: false, error: 'forbidden: this board answers its own pages only' });
            return;
          }
          readJsonBody(req)
            .then((body) => sendJson(res, 200, route === 'answer' ? handleAnswer(dir, body) : handleSettingsWrite(dir, route, body)))
            .catch((err) => {
              const known = err instanceof SettingsError;
              if (!known) console.error(`board: settings write failed: ${String(err?.message ?? err)}`);
              sendJson(res, known ? 400 : 500, {
                ok: false,
                error: String(err?.message ?? err),
                // Present only on a refusal the operator can answer, and it
                // carries the exact token that answers it.
                ...(err?.widens === true ? { widens: true, confirm_with: err.confirm_with } : {}),
              });
            });
          return;
        }
        // Spend is served, never rendered into the artefacts. It is derived
        // from transcripts under the operator's home directory — machine-local
        // by nature — so putting it in board.json would make two clones of one
        // journal disagree and break the byte-exact `--check` contract. The
        // page fetches this route and simply omits the section when the fetch
        // fails, which is what happens over file://.
        if (req.url === '/cost.json' || req.url.startsWith('/cost.json?')) {
          let body;
          try {
            // The window is the ONLY query parameter, and it is validated
            // against a closed list rather than passed through — an unknown
            // value falls back to `all` instead of reaching the report, so a
            // hand-typed URL cannot produce a window nobody defined.
            const asked = new URLSearchParams(req.url.slice(req.url.indexOf('?') + 1)).get('window');
            const window = WINDOWS.includes(asked) ? asked : 'all';
            // `flags.transcripts` is [] unless the operator started this
            // server with `--transcripts`; costReport falls through to
            // `spend.transcript_dirs` and then the derived directory on its
            // own, so an empty array here changes nothing for the common case.
            body = costJson(costReport({ tyranDir: dir, transcriptDirs: flags.transcripts, window }));
          } catch (err) {
            // A cost failure must never take the board down with it: the
            // board answers "what is going on", and that answer does not
            // depend on knowing what it cost.
            res.writeHead(503, { 'content-type': 'application/json; charset=utf-8' });
            res.end(JSON.stringify({ schema: COST_SCHEMA, error: String(err?.message ?? err) }) + '\n');
            return;
          }
          res.writeHead(200, { 'content-type': 'application/json; charset=utf-8' });
          res.end(body);
          return;
        }
        const { files } = renderAll(dir);
        if (req.url === '/' || req.url === '/index.html') {
          res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
          res.end(files[BOARD_HTML_FILE]);
        } else if (req.url === '/board.json') {
          res.writeHead(200, { 'content-type': 'application/json; charset=utf-8' });
          res.end(files[BOARD_JSON_FILE]);
        } else {
          res.writeHead(404, { 'content-type': 'text/plain' });
          res.end('not found\n');
        }
      } catch (err) {
        // Readable, and 200 on purpose. The page refreshes itself every 30
        // seconds, so a plain-text 500 becomes a browser tab re-fetching an
        // error nobody can act on twice a minute. The state that reaches here
        // is real and fixable — over the initiative ceiling, an unreadable
        // state directory — and the operator needs the sentence, not a status
        // code they will never see.
        res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
        res.end(renderBoardError(String(err?.message ?? err)));
      }
    });
    // A busy port is an ordinary operator mistake, not a crash worth a stack
    // trace over.
    server.on('error', (err) => {
      console.error(
        err?.code === 'EADDRINUSE'
          ? `board: port ${flags.port} is already in use — pass --port <n> for another`
          : `board: could not serve: ${String(err?.message ?? err)}`,
      );
      process.exitCode = 2;
    });
    server.listen(flags.port, '127.0.0.1', () => {
      const url = urlFor(flags.port);
      // Written from INSIDE the listen callback, so the record only ever
      // describes a server that actually bound a port — a record written
      // before this point would be an intention, and `--stop` would signal
      // whatever inherited the pid of a board that never started.
      writeServerRecord(dir, { pid: process.pid, port: flags.port, url, write: flags.write, started_at: new Date().toISOString() });
      console.log(
        `board: serving ${url} ` +
          `(${flags.write ? 'Settings can edit config.yaml and autonomy.yaml' : 'read-only'}; Ctrl-C to stop)`,
      );
      if (flags.open) openInBrowser(url);
    });
    // Clear the record on the way out, so the next caller does not have to
    // probe a port to learn that this one is gone. Best-effort: a killed
    // process runs none of this, which is exactly why the reader treats the
    // record as a hint and the health probe as the answer.
    const clear = () => { removeServerRecord(dir); };
    process.on('exit', clear);
    for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
      process.on(signal, () => {
        clear();
        process.exit(0);
      });
    }
    // A board whose directory is gone is serving nothing, and nothing will
    // ever ask it to stop: `--stop` needs a `.tyran` to find the record in,
    // and the operator who deleted the checkout is not going to hunt a pid.
    // Detached servers are started automatically now, so "nobody ever stops
    // it" is the DEFAULT case rather than an unlucky one — a deleted worktree
    // otherwise leaves a process holding a port until the machine reboots.
    const watchdog = setInterval(() => {
      if (!existsSync(dir)) {
        clear();
        process.exit(0);
      }
    }, DIR_WATCHDOG_MS);
    // Unref'd so it is the SERVER that keeps this process alive, never the
    // timer: a watchdog that held the loop open would turn every exit path
    // above into a hang.
    watchdog.unref?.();
    return;
  }

  let rendered;
  try {
    rendered = renderAll(dir);
  } catch (err) {
    console.error(`board: ${err.message}`);
    process.exit(2);
  }

  if (flags.check) {
    let drift = 0;
    for (const [name, content] of Object.entries(rendered.files)) {
      const verdict = checkFile(join(outDir, name), content);
      if (!verdict.ok) {
        drift++;
        console.error(`board: drift: ${join(outDir, name)} — ${verdict.reason}`);
      }
    }
    if (drift > 0) {
      console.error(`board: regenerate with: node scripts/board.mjs --dir ${dir}`);
      process.exit(1);
    }
    console.log(`board: projections up to date (3 files in ${outDir})`);
    return;
  }

  writeAllAtomic(Object.entries(rendered.files).map(([name, content]) => [join(outDir, name), content]));
  for (const name of Object.keys(rendered.files)) console.log(`wrote ${join(outDir, name)}`);
}

function canonicalPath(path) {
  const abs = resolve(path);
  try {
    return realpathSync(abs);
  } catch {
    return abs;
  }
}

function isMainModule(moduleUrl) {
  if (!process.argv[1]) return false;
  return canonicalPath(process.argv[1]) === canonicalPath(fileURLToPath(moduleUrl));
}

if (isMainModule(import.meta.url)) main();
