/**
 * Open the served board in the operator's browser.
 *
 * The board was a URL printed to a terminal that nothing ever opened, and for
 * the people this matters most to that is several steps — keep this window
 * running, now type that address somewhere else — each one a place to stop.
 * The dashboard is where Tyran becomes legible, and it was the one thing
 * installation never actually reached.
 *
 * Best-effort and never fatal: a failure here leaves the server running and
 * the URL printed, which is exactly where things were before. Headless
 * machines, SSH sessions and locked-down desktops all land in that branch and
 * none of them is an error worth taking a working server down for.
 *
 * The argument vector is fixed and the URL is the only variable — it is built
 * from a port this process is already listening on, never from user text —
 * and `shell: false` (the default) means nothing here reaches a shell.
 */
export function openInBrowser(url, { platform = process.platform, spawn = spawnProcess } = {}) {
  const [command, args] =
    platform === 'darwin' ? ['open', [url]]
      : platform === 'win32' ? ['cmd', ['/c', 'start', '', url]]
        : ['xdg-open', [url]];
  try {
    const child = spawn(command, args, { stdio: 'ignore', detached: true });
    // A missing `open`/`xdg-open` arrives as an async error event, not a
    // throw, so the catch below would never see it — and an unhandled one
    // would take the server down, which is the opposite of best-effort.
    child.on?.('error', () => { /* no browser here; the printed URL still works */ });
    child.unref?.();
    return true;
  } catch {
    return false;
  }
}

/** Same ceiling as the evidence gate's journal locator — a deliberate
 * duplicate: scripts must not import from hook files (direction is
 * hooks -> scripts), and the constant is one number with one meaning. */
export const MAX_INITIATIVES = 64;

const GENERATED_MD_HEADER =
  '<!-- GENERATED by tyran scripts/board.mjs - DO NOT EDIT. Source of truth: the journals under .tyran/state/ -->\n' +
  '<!-- Regenerate: node scripts/board.mjs --dir <.tyran> -->\n';

class UsageError extends Error {}

/** Every initiative folded to its board; failures become visible entries. */
export function readInitiativeBoards(tyranDir) {
  const stateDir = join(tyranDir, 'state');
  let names;
  try {
    names = readdirSync(stateDir).sort();
  } catch (err) {
    // ENOENT is the legitimate fresh-repo case: setup has run, no initiative
    // exists yet, and an empty board is the right answer. Anything else —
    // EACCES, ENOTDIR, EIO — means we cannot TELL whether there is work here,
    // and returning "no initiatives" for that is the board saying all is well
    // about a directory it could not open. It is also what `--dir` pointed at
    // the repo root instead of at `.tyran` looks like.
    if (err?.code === 'ENOENT') return { initiatives: [], errors: [] };
    return { initiatives: [], errors: [{ name: 'state', error: `${err?.code ?? 'unreadable'} reading ${join(basename(resolve(tyranDir)), 'state')}` }] };
  }
  const dirs = names.filter((name) => {
    try {
      return statSync(join(stateDir, name)).isDirectory();
    } catch {
      return false;
    }
  });
  if (dirs.length > MAX_INITIATIVES) {
    throw new UsageError(
      `${dirs.length} initiative directories under ${stateDir} — the ceiling is ${MAX_INITIATIVES}. ` +
        'Archive closed initiatives out of state/ before rendering a board over them.',
    );
  }
  const initiatives = [];
  const errors = [];
  const warned = [];
  for (const name of dirs) {
    const journal = join(stateDir, name, 'journal.jsonl');
    // "there is no journal here" and "I cannot tell whether there is a journal
    // here" are different facts, and `existsSync` returns false for both. An
    // initiative in an unreadable directory used to vanish from the board with
    // nothing said — the totals simply went down by one.
    try {
      statSync(journal);
    } catch (err) {
      if (err?.code === 'ENOENT') continue;
      errors.push({ name, error: `${err?.code ?? 'unreadable'} reading ${join('state', name, 'journal.jsonl')}` });
      continue;
    }
    try {
      const state = fold(readJournal(journal));
      // PARTIAL damage, which the guard below cannot see. That guard fires only
      // when NOTHING was readable; three good tickets plus one unparseable line
      // folds to a board with no errors on it and renders as an initiative in
      // perfect health. `warnings()` has produced exactly the right sentences
      // for this since the projection layer existed — the board simply never
      // asked for them. A page whose stated reason to exist is not saying "all
      // is well" when it is not cannot be silent about the damaged half.
      const flaws = warnings(state);
      if (flaws.length > 0) warned.push({ name, warnings: flaws });
      // `readJournal` does NOT throw on unparseable content — it returns zero
      // events and counts the damage — so the catch below never sees a corrupt
      // journal. Without this guard a damaged file renders as an initiative
      // with nothing wrong, which is the one output this board must never
      // produce. Same condition the CLI and the refresh probe refuse on.
      if (state.total === 0 && (state.corruptLines + state.malformed > 0 || state.truncatedTail)) {
        const damage = [
          state.corruptLines > 0 ? `${state.corruptLines} corrupt line(s)` : null,
          state.malformed > 0 ? `${state.malformed} non-object line(s)` : null,
          state.truncatedTail ? 'a truncated final line' : null,
        ].filter(Boolean).join(', ');
        errors.push({ name, error: `0 readable events and ${damage} — the journal is damaged` });
        continue;
      }
      // `journal` is returned, not re-derived by consumers: answer.mjs writes
      // to the file this function already located, so there is one rule for
      // where an initiative's journal lives (ADR-21).
      initiatives.push({ name, journal, state, board: boardOf(state), files: initiativeFiles(tyranDir, name) });
    } catch (err) {
      // The CODE and a repo-relative path, never the raw message. A Node fs
      // error carries the absolute path, which means a home directory and a
      // username — and this string is written into `board.json`, a committed
      // artefact compared byte for byte, so it also made `--check` fail on any
      // other machine.
      errors.push({
        name,
        error: err?.code
          ? `${err.code} reading ${join('state', name, 'journal.jsonl')}`
          : String(err?.message ?? err),
      });
    }
  }
  return { initiatives, errors, warned };
}

/**
 * The files an initiative ACTUALLY has beside its journal.
 *
 * Named set, `existsSync`, no creation and no guessing: the operator asked to
 * reach an agent's plan from the board and asked in the same breath that
 * nothing be created to satisfy the link. A listed file that is not there is
 * the same lie as a missing one, in the other direction.
 *
 * The recorded path is REPO-RELATIVE, and that is not cosmetic: `board.json`
 * is a committed, byte-compared artefact, so an absolute path would make two
 * clones of one journal disagree and fail `--check` on a machine whose home
 * directory is spelled differently. It is the same reason spend is served
 * rather than embedded. Relative is also the more useful form — it is what
 * the reader pastes, from the repo root, into an editor.
 *
 * These five ARE served, since 0.1.42, by `readInitiativeDoc` below — and the
 * promise this comment has always made survives it intact: `--serve` still
 * derives a filesystem path from no URL at all. The route takes a NAME and
 * matches it against the list above, exactly as the one route that writes —
 * Settings, behind `--write` — reaches two fixed files named in `settings.mjs`
 * by taking a KEY from the request and never a path.
 */
export const INITIATIVE_FILES = Object.freeze(['PLAN.md', 'NOTES.md', 'RETRO.md', 'STATE.md', 'PROGRESS.md']);

export function initiativeFiles(tyranDir, name) {
  const dir = join(tyranDir, 'state', name);
  const shown = join(basename(resolve(tyranDir)), 'state', name);
  return INITIATIVE_FILES.filter((file) => existsSync(join(dir, file))).map((file) => ({
    name: file,
    path: join(shown, file),
  }));
}

/**
 * How much of one document travels to the page, in CODEPOINTS.
 *
 * Codepoints and not bytes because the cut is applied to a decoded string:
 * slicing a UTF-8 buffer at a fixed offset lands inside a character often
 * enough, and hands the reader a replacement mark that was never in the file.
 *
 * A cap at all because this route reads whatever grew beside a journal, and a
 * NOTES.md three weeks into an initiative is not a thing to push through one
 * response. The panel says it was cut and names the path holding the rest.
 */
export const MAX_DOC_CHARS = 200_000;

/**
 * One initiative document, for the page's file viewer.
 *
 * TWO CLOSED SETS AND NO PATH ARITHMETIC — that is the whole security story,
 * and it is why the comment on `initiativeFiles` above ("nothing is served
 * from here") could be revisited rather than merely broken. `name` must equal
 * a member of `INITIATIVE_FILES`, and `init` must equal a directory that
 * `state/` actually contains, compared against the very listing the board
 * folds. Nothing from the request is joined into a path until it has matched
 * one of those two lists, so `..`, an absolute path, a NUL and a name that
 * differs only by case are all rejected by never becoming candidates — not by
 * a filter someone has to keep ahead of the next trick.
 *
 * The text is invisible-ESCAPED, like every other journal-side value that
 * reaches a human (invisible.mjs): these documents are written by agents out
 * of reports about foreign repositories, and the reader is looking at them on
 * a page instead of in the editor that would have shown the same bytes.
 *
 * Nothing is echoed back on a refusal. A message naming what was asked for is
 * a message carrying attacker-chosen text into the operator's browser, and
 * naming the five files it DOES serve is more useful anyway.
 */
export function readInitiativeDoc(tyranDir, init, name) {
  if (!INITIATIVE_FILES.includes(name)) {
    return { ok: false, status: 400, error: `this board serves only: ${INITIATIVE_FILES.join(', ')}` };
  }
  const stateDir = join(tyranDir, 'state');
  let names;
  try {
    names = readdirSync(stateDir);
  } catch (err) {
    return { ok: false, status: 503, error: `${err?.code ?? 'unreadable'} reading the state directory` };
  }
  if (!names.includes(init)) {
    return { ok: false, status: 404, error: 'no initiative by that name in this board' };
  }
  const file = join(stateDir, init, name);
  let raw;
  try {
    raw = readFileSync(file, 'utf8');
  } catch (err) {
    // ENOENT here is ordinary: `initiativeFiles` listed what existed when the
    // page was rendered, and an initiative that has since been archived is a
    // fact to report rather than a failure.
    return {
      ok: false,
      status: err?.code === 'ENOENT' ? 404 : 503,
      error: err?.code === 'ENOENT'
        ? `${name} is not beside that journal — the board lists what exists when it renders, so reload it`
        : `${err?.code ?? 'unreadable'} reading ${name}`,
    };
  }
  const chars = [...raw];
  const truncated = chars.length > MAX_DOC_CHARS;
  return {
    ok: true,
    status: 200,
    schema: 1,
    init,
    name,
    // Repo-relative, the same form `initiativeFiles` records and for the same
    // reason: it is what the reader pastes into an editor, and it names no
    // home directory.
    path: join(basename(resolve(tyranDir)), 'state', init, name),
    truncated,
    chars: truncated ? MAX_DOC_CHARS : chars.length,
    text: escapeInvisible(truncated ? chars.slice(0, MAX_DOC_CHARS).join('') : raw),
  };
}

/** Pure merge of per-initiative boards into the one payload. */
/**
 * How many logged errors travel in the payload.
 *
 * `board.json` is committed and compared byte for byte, so an unbounded list
 * would grow the artefact with every bad night. Newest first and a count for
 * the rest: the board's job is to say something is wrong, not to be the log.
 */
export const MAX_LOGGED_ERRORS = 20;

export function crossBoard({ initiatives, errors, warned = [], stop = null }) {
  const asks = [];
  const summaries = [];
  const agents = [];
  const paused = [];
  const logged = [];
  const files = {};
  const lanes = Object.fromEntries(LANES.map((lane) => [lane, []]));
  let merged = 0;
  let tickets = 0;
  let asOf = null;

  for (const { name, state, board, files: docs } of initiatives) {
    merged += state.merged;
    tickets += state.ticketList.length;
    // Per-initiative, because one blended percentage over every initiative is
    // not a fact about any of them: an operator reading "50%" across four
    // slugs cannot tell which is nearly done from which has not started.
    //
    // The TITLE is the point of the row. `init.created` has carried a written
    // sentence all along — "Settings on the board: edit config and the
    // autonomy policy from the page" — and the board showed the directory
    // slug. `waiting` and `last_ts` are here rather than a computed idle time
    // because this payload is byte-compared under `--check` and reads no
    // clock; the page ages them, exactly as it already ages agents.
    summaries.push({
      name,
      title: typeof state.created?.data?.title === 'string' ? state.created.data.title : null,
      tickets: state.ticketList.length,
      merged: state.merged,
      percent: state.percent,
      waiting: board.asks.length,
      // A COUNT, and deliberately not the findings themselves. Measured across
      // 63 distinct real journals: 3 carry any finding at all, 49 in total,
      // and NOT ONE names a ticket — so they cannot enrich a card, which is
      // where a richer board would have put them. Their median claim is 429
      // characters, a paragraph rather than a label, and STATE.md already
      // renders the full seven-column table.
      //
      // So this is a pointer, not a copy: the research exists and the reader
      // is told where. Duplicating the prose here would be ADR-21's defect
      // and would cost ~600 B per finding in a byte-compared payload.
      // Guarded: `crossBoard` is exported and takes any folded state, and a
      // caller assembling one by hand need not have every collection. A
      // missing array must read as "none", never take the board down.
      findings: (state.findings ?? []).length,
      // FINISHED and ABANDONED read identically on a percentage bar, and they
      // are the opposite situation: one is work that ended, the other is work
      // that stopped. The board had no way to tell them apart — measured, it
      // is the same 63 journals where 43 sat on an unanswered question and 6
      // were genuinely done.
      //
      // A checkpoint whose phase is the reserved word `closed` is the ONLY
      // event that declares an initiative over (journal.mjs), which is already
      // what closes its still-open spawns — so this hangs on that same fact
      // rather than inventing a second rule for "finished" (ADR-21). The
      // TIMESTAMP, not a boolean: "closed 9 days ago" is the reading, and the
      // page ages it in the reader's browser like every other time here.
      //
      // `phase` travels beside it because an initiative that is NOT closed
      // still has its own word for where it is, and the per-initiative
      // board.json has carried that word all along while the cross board
      // showed a percentage and nothing else.
      //
      // NOT deployment: nothing in the closed event set records a deploy, so
      // the board must not imply one. This says the initiative was wound up.
      phase: state.checkpoint?.phase ?? null,
      closed: isClosingPhase(state.checkpoint?.phase) ? state.checkpoint.ts : null,
      last_ts: state.lastTs,
    });
    if (state.lastTs !== null && (asOf === null || state.lastTs > asOf)) asOf = state.lastTs;
    for (const a of board.asks) asks.push({ ...a, init: name });
    for (const a of board.agents) agents.push({ ...a, init: name });
    if (board.paused !== null) paused.push({ ...board.paused, init: name });
    if (docs !== undefined && docs.length > 0) files[name] = docs;
    // An `error` event with no ticket landed in STATE.md's Errors table and
    // nowhere else: the fold collects it, and the board that exists to say
    // "not all is well" carried neither `state.errors` nor the tickets an
    // error named that the journal has never seen. A whole class of agent
    // failure was invisible on the one screen meant to show it.
    for (const e of state.errors) {
      logged.push({
        init: name,
        class: e.class,
        detail: e.detail,
        ticket: e.ticket ?? null,
        ticket_unknown: e.ticket_unknown === true,
        ts: e.ts,
        actor: e.actor,
      });
    }
    for (const lane of LANES) {
      for (const card of board.lanes.get(lane)) lanes[lane].push({ ...card, init: name });
    }
  }
  // The SAME rule the answer sheet uses, imported rather than restated: the
  // sheet and the page are two renderings of one queue, and two orderings
  // would make an operator answer them in different sequences depending on
  // which surface they happened to open (ADR-21).
  const ordered = sortAsks(asks);
  asks.length = 0;
  asks.push(...ordered);
  // Stalest FIRST. Rendering agents in the order the journals happened to spawn
  // them puts the one that has said nothing for six hours anywhere at all,
  // including last — and the whole reason the strip carries a last-signal time
  // is that the silent agent is the one worth looking at. `last_signal` is an
  // ISO string from the journal, so ascending string order IS ascending time;
  // an agent with no signal at all sorts to the front, where it belongs.
  // Sorted on EVIDENCE where there is any, falling back to the signal. An
  // agent that has shown nothing for three hours belongs at the top even if it
  // has been saying "working" every four minutes the whole time — which is
  // exactly the case the old signal-only sort put last.
  agents.sort((a, b) =>
    String(a.last_evidence ?? a.since ?? '').localeCompare(String(b.last_evidence ?? b.since ?? '')));
  // Newest first: an error from four days ago is history, the one from ten
  // minutes ago is the reason you opened this page.
  logged.sort((a, b) => String(b.ts ?? '').localeCompare(String(a.ts ?? '')));

  return {
    schema: 1,
    as_of: asOf,
    totals: {
      initiatives: initiatives.length,
      agents: agents.length,
      // Of those, how many the journal has moved on without. `agents` counts
      // OPEN spawns, which is what it has always counted and what the strip
      // lists — but presenting that number as "running" made a week-old ghost
      // indistinguishable from an agent working right now, and an overnight
      // operator reads this tile before anything else on the page.
      agents_stale: agents.filter((a) => a.stale === true).length,
      merged,
      tickets,
      percent: tickets === 0 ? 0 : Math.round((merged / tickets) * 100),
      // Counted here rather than on the page, from BOTH sources of "a human is
      // needed": the lanes, and the agents. A ticket parked by a `ticket.status`
      // override leaves no card in `blocked` — the override is resolved before
      // the blockage in `boardOf` — so an agent could sit blocked on it while a
      // tile counting lanes alone read zero. It did.
      blocked: lanes.blocked.length + lanes['changes-requested'].length
        + agents.filter((a) => a.state === 'blocked').length,
    },
    // Committed repo state, so it belongs in the artefact rather than behind a
    // route: `.tyran/STOP` is identical in every clone, and `--check` stays
    // byte-exact. The machine-local half of "is this run supposed to be
    // running" — the pause marker, the resume watcher — is served instead,
    // for the same reason spend is.
    // `{stopped, reason}` and NOT the path `checkStopAt` also returns: an
    // absolute path in a committed, byte-compared artefact makes two clones of
    // one journal disagree on a machine whose home directory is spelled
    // differently. The same trap the initiative file list was caught in.
    stop: stop === null ? null : { stopped: stop.stopped, reason: stop.reason },
    paused,
    asks,
    // Ordered by directory name, like everything else here, so two renders of
    // one journal set are byte-identical. `totals.percent` blends these; the
    // rows are what let a reader see WHICH initiative it blends.
    initiatives: summaries,
    agents,
    files,
    lanes,
    // The key is `errors_logged`, NOT `errors`: `errors` on this payload
    // already means "this initiative's journal could not be read at all", and
    // one key with two meanings is the defect ADR-21 is named after.
    errors_logged: logged.slice(0, MAX_LOGGED_ERRORS),
    errors_logged_total: logged.length,
    errors,
    warned,
  };
}

export function crossJson(payload) {
  return jsonEscapeInvisible(JSON.stringify(payload, null, 2)) + '\n';
}

export function renderCrossMd(payload) {
  const parts = [GENERATED_MD_HEADER, '# BOARD — all initiatives\n\n'];
  const t = payload.totals;
  // "open", not "running": the headline used to assert that every open spawn
  // was live work, and the stale ones are named right after it rather than
  // being quietly dropped from the count (ADR-19 correction 1).
  parts.push(
    `**${t.agents} agent(s) open across ${t.initiatives} initiative(s)` +
      `${t.agents_stale > 0 ? `, ${t.agents_stale} stale` : ''} · ` +
      `${t.merged}/${t.tickets} tickets merged (${t.percent}%) · as of ${inline(payload.as_of)}**\n`,
  );
  // First, and above the pause: a STOP outranks everything. It is the one
  // state where a strip of silent agents is the system doing as it was told.
  if (payload.stop?.stopped === true) {
    parts.push(`\n**STOPPED** — an operator halted this repo: ${inline(payload.stop.reason)}\n`);
  }
  for (const p of payload.paused) {
    parts.push(`\n**PAUSED** — ${inline(p.init)}: gate ${inline(p.kind)} (${inline(p.result)}) since ${inline(p.since)}\n`);
  }
  for (const e of payload.errors) {
    parts.push(`\n**UNREADABLE** — ${inline(e.name)}: ${inline(e.error)}\n`);
  }
  for (const d of payload.warned ?? []) {
    for (const w of d.warnings) parts.push(`\n**WARNING** — ${inline(d.name)}: ${inline(w)}\n`);
  }
  for (const e of payload.errors_logged ?? []) {
    const what = `${inline(e.class ?? 'error')}${e.detail != null ? `: ${inline(e.detail)}` : ''}` +
      (e.ticket_unknown ? ` — it names ticket ${inline(e.ticket)}, which this journal has never declared` : '');
    parts.push(`\n**ERROR** — ${inline(e.init)}: ${what} (${inline(e.ts)})\n`);
  }
  const hidden = (payload.errors_logged_total ?? 0) - (payload.errors_logged ?? []).length;
  if (hidden > 0) parts.push(`\n**ERROR** — and ${hidden} older error(s); read the journals for the rest\n`);

  parts.push('\n## Waiting on you\n\n');
  if (payload.asks.length === 0) parts.push('_none — the agents have what they need_\n');
  for (const a of payload.asks) {
    parts.push(`- **${inline(a.question ?? `(no question recorded — gate ${a.kind})`)}**\n`);
    if (a.recommendation != null) parts.push(`  - recommendation: ${inline(a.recommendation)}\n`);
    if (a.default != null) parts.push(`  - default: ${inline(a.default)}\n`);
    if (a.blocks != null && a.blocks.count > 0) {
      parts.push(`  - blocks ${a.blocks.count} ticket(s): ${a.blocks.ids.map((id) => inline(id)).join(', ')}\n`);
    }
    parts.push(`  - ${inline(a.init)}${a.ticket != null ? ` · \`${inline(a.ticket)}\`` : ''} · since ${inline(a.since)}\n`);
  }

  parts.push('\n## Agents\n\n');
  if (payload.agents.length === 0) parts.push('_none running_\n');
  for (const a of payload.agents) {
    parts.push(
      `- \`${inline(a.agent)}\` (${inline(a.role)}) — ${inline(a.init)}` +
        `${a.ticket != null ? ` · \`${inline(a.ticket)}\`` : ''} · ${inline(a.state)}` +
        `${a.detail != null ? ` — ${inline(a.detail)}` : ''} · started ${inline(a.since)}` +
        `${a.last_signal != null ? ` · last signal ${inline(a.last_signal)}` : ''}` +
        `${a.next != null ? ` · next: ${inline(a.next)}` : ''}\n`,
    );
  }

  const withFiles = Object.keys(payload.files ?? {}).sort();
  if (withFiles.length > 0) {
    parts.push('\n## Files\n\n');
    for (const name of withFiles) {
      parts.push(`- ${inline(name)}: ${payload.files[name].map((f) => `\`${inline(f.name)}\``).join(', ')}\n`);
    }
  }

  for (const lane of LANES) {
    const cards = payload.lanes[lane];
    parts.push(`\n## ${lane} (${cards.length})\n\n`);
    if (cards.length === 0) {
      parts.push('_none_\n');
      continue;
    }
    for (const c of cards) {
      parts.push(
        `- \`${inline(c.id)}\`${c.title ? ` — ${inline(c.title)}` : ''} _(${inline(c.init)})_` +
          `${c.agents.length > 0 ? ` — ${inline(c.agents)}` : ''}` +
          `${c.annotation ? ` — ${inline(c.annotation)}` : ''}\n`,
      );
    }
  }
  return parts.join('');
}

