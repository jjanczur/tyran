#!/usr/bin/env node
/**
 * board — the cross-initiative kanban view.
 *
 * `project.mjs` renders one initiative's BOARD.md/board.json next to its
 * journal; this tool folds EVERY journal under `.tyran/state/` into one
 * board — the answer to "what is going on" that previously required opening
 * one file per initiative (measured install: 31). Three artefacts, all
 * GENERATED, all under `state/` where the AUTO policy class already covers
 * them:
 *
 *   .tyran/state/BOARD.md     the agent/git surface
 *   .tyran/state/board.json   schema 1, for tooling
 *   .tyran/state/board.html   the page an operator stares at (board-html.mjs)
 *
 * Determinism carries over from the projection layer: no clock (the page
 * shows the newest event ts as "as of"), byte-identical reruns, invisibles
 * escaped never removed, `--check` compares bytes. An unreadable journal is a
 * visible error entry, never a crash — a board that omits a broken
 * initiative reads as "all is well" exactly when it is not.
 *
 * CLI:
 *   node board.mjs [--dir <.tyran>] [--check] [--serve [--port <n>]]
 * Exit: 0 ok · 1 drift (--check) · 2 usage/IO
 */
import { existsSync, readdirSync, statSync, readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { join, resolve } from 'node:path';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readJournal } from './journal.mjs';
import {
  BOARD_FILE,
  BOARD_JSON_FILE,
  LANES,
  boardOf,
  checkFile,
  fold,
  inline,
  writeAllAtomic,
} from './project.mjs';
import { jsonEscapeInvisible } from './invisible.mjs';
import { renderBoardHtml } from './board-html.mjs';

export const BOARD_HTML_FILE = 'board.html';

/** Same ceiling as the evidence gate's journal locator — a deliberate
 * duplicate: scripts must not import from hook files (direction is
 * hooks -> scripts), and the constant is one number with one meaning. */
export const MAX_INITIATIVES = 64;

const GENERATED_MD_HEADER =
  '<!-- GENERATED by tyran scripts/board.mjs - DO NOT EDIT. Source of truth: the journals under .tyran/state/ -->\n' +
  '<!-- Regenerate: node scripts/board.mjs --dir <.tyran> -->\n';

class UsageError extends Error {}

/** Every initiative folded to its board; failures become visible entries. */
export function readInitiativeBoards(tyranDir) {
  const stateDir = join(tyranDir, 'state');
  let names;
  try {
    names = readdirSync(stateDir).sort();
  } catch {
    return { initiatives: [], errors: [] };
  }
  const dirs = names.filter((name) => {
    try {
      return statSync(join(stateDir, name)).isDirectory();
    } catch {
      return false;
    }
  });
  if (dirs.length > MAX_INITIATIVES) {
    throw new UsageError(
      `${dirs.length} initiative directories under ${stateDir} — the ceiling is ${MAX_INITIATIVES}. ` +
        'Archive closed initiatives out of state/ before rendering a board over them.',
    );
  }
  const initiatives = [];
  const errors = [];
  for (const name of dirs) {
    const journal = join(stateDir, name, 'journal.jsonl');
    if (!existsSync(journal)) continue;
    try {
      const state = fold(readJournal(journal));
      initiatives.push({ name, state, board: boardOf(state) });
    } catch (err) {
      errors.push({ name, error: String(err?.message ?? err) });
    }
  }
  return { initiatives, errors };
}

/** Pure merge of per-initiative boards into the one payload. */
export function crossBoard({ initiatives, errors }) {
  const asks = [];
  const agents = [];
  const paused = [];
  const lanes = Object.fromEntries(LANES.map((lane) => [lane, []]));
  let merged = 0;
  let tickets = 0;
  let asOf = null;

  for (const { name, state, board } of initiatives) {
    merged += state.merged;
    tickets += state.ticketList.length;
    if (state.lastTs !== null && (asOf === null || state.lastTs > asOf)) asOf = state.lastTs;
    for (const a of board.asks) asks.push({ ...a, init: name });
    for (const a of board.agents) agents.push({ ...a, init: name });
    if (board.paused !== null) paused.push({ ...board.paused, init: name });
    for (const lane of LANES) {
      for (const card of board.lanes.get(lane)) lanes[lane].push({ ...card, init: name });
    }
  }
  asks.sort((a, b) => String(a.since ?? '').localeCompare(String(b.since ?? '')));

  return {
    schema: 1,
    as_of: asOf,
    totals: {
      initiatives: initiatives.length,
      agents: agents.length,
      merged,
      tickets,
      percent: tickets === 0 ? 0 : Math.round((merged / tickets) * 100),
    },
    paused,
    asks,
    agents,
    lanes,
    errors,
  };
}

export function crossJson(payload) {
  return jsonEscapeInvisible(JSON.stringify(payload, null, 2)) + '\n';
}

export function renderCrossMd(payload) {
  const parts = [GENERATED_MD_HEADER, '# BOARD — all initiatives\n\n'];
  const t = payload.totals;
  parts.push(
    `**${t.agents} agent(s) running across ${t.initiatives} initiative(s) · ` +
      `${t.merged}/${t.tickets} tickets merged (${t.percent}%) · as of ${inline(payload.as_of)}**\n`,
  );
  for (const p of payload.paused) {
    parts.push(`\n**PAUSED** — ${inline(p.init)}: gate ${inline(p.kind)} (${inline(p.result)}) since ${inline(p.since)}\n`);
  }
  for (const e of payload.errors) {
    parts.push(`\n**UNREADABLE** — ${inline(e.name)}: ${inline(e.error)}\n`);
  }

  parts.push('\n## Waiting on you\n\n');
  if (payload.asks.length === 0) parts.push('_none — the agents have what they need_\n');
  for (const a of payload.asks) {
    parts.push(`- **${inline(a.question ?? `(no question recorded — gate ${a.kind})`)}**\n`);
    if (a.recommendation != null) parts.push(`  - recommendation: ${inline(a.recommendation)}\n`);
    if (a.default != null) parts.push(`  - default: ${inline(a.default)}\n`);
    parts.push(`  - ${inline(a.init)}${a.ticket != null ? ` · \`${inline(a.ticket)}\`` : ''} · since ${inline(a.since)}\n`);
  }

  parts.push('\n## Agents\n\n');
  if (payload.agents.length === 0) parts.push('_none running_\n');
  for (const a of payload.agents) {
    parts.push(
      `- \`${inline(a.agent)}\` (${inline(a.role)}) — ${inline(a.init)}` +
        `${a.ticket != null ? ` · \`${inline(a.ticket)}\`` : ''} · ${inline(a.state)}` +
        `${a.detail != null ? ` — ${inline(a.detail)}` : ''} · last signal ${inline(a.last_signal)}\n`,
    );
  }

  for (const lane of LANES) {
    const cards = payload.lanes[lane];
    parts.push(`\n## ${lane} (${cards.length})\n\n`);
    if (cards.length === 0) {
      parts.push('_none_\n');
      continue;
    }
    for (const c of cards) {
      parts.push(
        `- \`${inline(c.id)}\`${c.title ? ` — ${inline(c.title)}` : ''} _(${inline(c.init)})_` +
          `${c.agents.length > 0 ? ` — ${inline(c.agents)}` : ''}` +
          `${c.annotation ? ` — ${inline(c.annotation)}` : ''}\n`,
      );
    }
  }
  return parts.join('');
}

export function renderAll(tyranDir) {
  const payload = crossBoard(readInitiativeBoards(tyranDir));
  const json = crossJson(payload);
  return {
    payload,
    files: {
      [BOARD_FILE]: renderCrossMd(payload),
      [BOARD_JSON_FILE]: json,
      [BOARD_HTML_FILE]: renderBoardHtml(json.trimEnd()),
    },
  };
}

// ------------------------------------------------------------------- CLI

const BOOLEAN_FLAGS = ['check', 'serve'];
const VALUE_FLAGS = ['dir', 'port'];

function parseArgs(argv) {
  const flags = { dir: '.tyran', port: 4173, check: false, serve: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith('--')) throw new UsageError(`unexpected argument "${arg}"`);
    const name = arg.slice(2);
    if (BOOLEAN_FLAGS.includes(name)) flags[name] = true;
    else if (VALUE_FLAGS.includes(name)) {
      const value = argv[i + 1];
      if (value === undefined) throw new UsageError(`flag --${name} needs a value`);
      flags[name] = name === 'port' ? Number(value) : value;
      i += 1;
    } else throw new UsageError(`unknown flag --${name}`);
  }
  if (!Number.isInteger(flags.port) || flags.port <= 0 || flags.port > 65535) {
    throw new UsageError('--port must be an integer in (0, 65535]');
  }
  return flags;
}

function main() {
  let flags;
  try {
    flags = parseArgs(process.argv.slice(2));
  } catch (err) {
    if (!(err instanceof UsageError)) throw err;
    console.error(`board: ${err.message}`);
    console.error('usage: board.mjs [--dir <.tyran>] [--check] [--serve [--port <n>]]');
    process.exit(2);
  }
  const dir = resolve(flags.dir);
  if (!existsSync(dir)) {
    console.error(`board: no such directory ${dir}`);
    process.exit(2);
  }
  const outDir = join(dir, 'state');

  if (flags.serve) {
    // Read-only, loopback-only, re-rendered per request so it is always
    // fresh. No filesystem path is ever derived from the URL.
    const server = createServer((req, res) => {
      try {
        const { files } = renderAll(dir);
        if (req.url === '/' || req.url === '/index.html') {
          res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
          res.end(files[BOARD_HTML_FILE]);
        } else if (req.url === '/board.json') {
          res.writeHead(200, { 'content-type': 'application/json; charset=utf-8' });
          res.end(files[BOARD_JSON_FILE]);
        } else {
          res.writeHead(404, { 'content-type': 'text/plain' });
          res.end('not found\n');
        }
      } catch (err) {
        res.writeHead(500, { 'content-type': 'text/plain' });
        res.end(`board render failed: ${String(err?.message ?? err)}\n`);
      }
    });
    server.listen(flags.port, '127.0.0.1', () => {
      console.log(`board: serving http://127.0.0.1:${flags.port}/ (read-only; Ctrl-C to stop)`);
    });
    return;
  }

  let rendered;
  try {
    rendered = renderAll(dir);
  } catch (err) {
    console.error(`board: ${err.message}`);
    process.exit(2);
  }

  if (flags.check) {
    let drift = 0;
    for (const [name, content] of Object.entries(rendered.files)) {
      const verdict = checkFile(join(outDir, name), content);
      if (!verdict.ok) {
        drift++;
        console.error(`board: drift: ${join(outDir, name)} — ${verdict.reason}`);
      }
    }
    if (drift > 0) {
      console.error(`board: regenerate with: node scripts/board.mjs --dir ${dir}`);
      process.exit(1);
    }
    console.log(`board: projections up to date (3 files in ${outDir})`);
    return;
  }

  writeAllAtomic(Object.entries(rendered.files).map(([name, content]) => [join(outDir, name), content]));
  for (const name of Object.keys(rendered.files)) console.log(`wrote ${join(outDir, name)}`);
}

function canonicalPath(path) {
  const abs = resolve(path);
  try {
    return realpathSync(abs);
  } catch {
    return abs;
  }
}

function isMainModule(moduleUrl) {
  if (!process.argv[1]) return false;
  return canonicalPath(process.argv[1]) === canonicalPath(fileURLToPath(moduleUrl));
}

if (isMainModule(import.meta.url)) main();
